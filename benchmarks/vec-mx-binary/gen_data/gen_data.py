#!/usr/bin/env python3
"""Generate vec-mx-binary/data.S from the fma_ref reference model.

Replaces gen_data.c + gen_data.sh, which used Spike.  Spike has no P3109 support,
and it could only produce FP8 arithmetic by going through BF16, which rounds twice
for 8-bit add/sub.  fma_ref computes each result exactly and rounds it once.

  ./gen_data.py --std ocp          > ../data.S   # OCP FP8 build
  ./gen_data.py --std p3109        > ../data.S   # P3109 build, extended domain
  ./gen_data.py --std p3109-finite > ../data.S   # P3109 build, finite domain
  ./gen_data.py --summary -o /dev/null           # show which input categories each array covers

The eight-bit array names (e4m3_*, e5m2_*) are kept so main.c compiles unchanged.
Under --std p3109 they carry binary8p4 and binary8p3 data respectively.

Every operation gets one array triple per rounding mode (_rne, _rtz, _rdn, _rup,
_rmm), with the same operands in all five.  FP16 and BF16 are unaffected by --std.
"""

import argparse
import os
import signal
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "common-data-gen"))

from gfloat.formats import format_info_bfloat16, format_info_binary16, format_info_binary32  # noqa: E402
from fma_ref import binary, binary_inputs  # noqa: E402
from gfloat_ref import FP8_STANDARDS, FRM, print_array, print_header, print_uint32  # noqa: E402

COUNT = 128
OPS = ("mul", "add", "sub", "wmul", "wadd", "wsub")   # w*: the result is twice as wide


def formats(std):
    """name -> (operand format, operand bytes, widened result format, its bytes)."""
    return {
        "fp16": (format_info_binary16, 2, format_info_binary32, 4),
        "bf16": (format_info_bfloat16, 2, format_info_binary32, 4),
        "e4m3": (FP8_STANDARDS[std]["altfmt0"], 1, format_info_bfloat16, 2),   # OCP E4M3 / binary8p4
        "e5m2": (FP8_STANDARDS[std]["altfmt1"], 1, format_info_bfloat16, 2),   # OCP E5M2 / binary8p3
    }


def emit(out, std, count, summary):
    print_header(out, f"Generated by gen_data.py --std {std} (fma_ref reference). Do not edit.")
    print_uint32(out, "N", count)
    for fname, (src, ssz, wide_fmt, wsz) in formats(std).items():
        for op in OPS:
            wide = op.startswith("w")
            base = op[1:] if wide else op
            dst, dsz = (wide_fmt, wsz) if wide else (src, ssz)
            pairs, taken = binary_inputs(base, src, dst, count)
            if summary:
                cov = ", ".join(f"{k} {v}" for k, v in taken.items() if v)
                print(f"{fname}_{op:5} [{src.name} -> {dst.name}]: {cov}", file=sys.stderr)
            a = [p[0] for p in pairs]
            b = [p[1] for p in pairs]
            for mode, (_frm, rnd) in FRM.items():
                res = [binary(base, src, dst, x, y, rnd) for x, y in pairs]
                name = f"{fname}_{op}_{mode}"
                print_array(out, name, "_a", a, ssz)
                print_array(out, name, "_b", b, ssz)
                print_array(out, name, "_out", res, dsz)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--std", choices=sorted(FP8_STANDARDS), default="ocp",
                    help="which 8-bit standard the altfmt slots carry (default: ocp)")
    ap.add_argument("-n", "--count", type=int, default=COUNT, help="elements per array (default: 128)")
    ap.add_argument("-o", "--output", help="write here instead of stdout")
    ap.add_argument("--summary", action="store_true", help="print the input categories of each array to stderr")
    args = ap.parse_args()
    out = open(args.output, "w") if args.output else sys.stdout
    try:
        emit(out, args.std, args.count, args.summary)
    finally:
        if args.output:
            out.close()


if __name__ == "__main__":
    signal.signal(signal.SIGPIPE, signal.SIG_DFL)
    main()
