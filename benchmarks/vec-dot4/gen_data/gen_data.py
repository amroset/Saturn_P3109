#!/usr/bin/env python3
"""Generate vec-dot4/data.S and vec-dot4/tests.h: vfdot4 (docs/vfdot4.md).

  ./gen_data.py -o ..        # writes ../data.S and ../tests.h

Each test runs vfdot4.vv or .vx at SEW 32 on N FP32 lanes, strip by strip
(8 << lmul lanes per strip), and checks every lane bit for bit. Per test:
  _a    vs2: four 8-bit codes per lane
  _b    vs1 (.vv): four codes per lane
  _f    .vx: one 64-bit scalar per strip, as two words: codes in bits 31:0,
        scale in 39:32, and in some tests random bits in 63:40
  _sa   vs2's scales, 32 bytes per strip (one register); lane l of a strip
        takes byte l >> lg, the other bytes are random
  _sb   vs1's scales (.vv), the same layout
  _c    the FP32 accumulators
  _m    v0, 4 bytes per strip (masked tests)
  _out  the expected vd: dot_vectors.expect (models/), or c where masked off
"""

import argparse
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "common-data-gen"))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "models"))

from gfloat_ref import FP8_STANDARDS, print_array, print_header  # noqa: E402
from dot_vectors import EDGE_S, dot, expect, finite_codes, near_c, pack  # noqa: E402

N = 64      # lanes per test; main.c's N
LANES = 8   # FP32 lanes per register (VLEN 256)
STD = "p3109"

# (form, scaled, alt, frm, lg, lmul, masked, garbage): lg = log2 E, lmul = log2 LMUL,
# garbage = random bits 63:40 in the .vx scalar
TESTS = (
    [("vv", 0, alt, 0, 0, 0, 0, 0) for alt in (0, 1)] +
    [("vv", 1, alt, rm, 0, 0, 0, 0) for alt in (0, 1) for rm in range(5)] +
    [("vx", 1, 0, rm, 0, 0, 0, 0) for rm in range(5)] + [("vx", 1, 1, 0, 0, 0, 0, 0)] +
    [("vx", 1, alt, 0, 0, 0, 0, 1) for alt in (0, 1)] +
    [("vx", 0, 0, 0, 0, 0, 0, 0)] +
    [("vv", 1, 0, 0, 1, 0, 0, 0), ("vv", 1, 1, 0, 3, 0, 0, 0), ("vx", 1, 1, 0, 1, 0, 0, 0), ("vx", 1, 0, 0, 3, 0, 0, 0)] +
    [("vv", 1, 0, 0, 0, 1, 0, 0), ("vv", 1, 1, 0, 0, 2, 0, 0), ("vx", 1, 1, 0, 0, 1, 0, 0), ("vx", 1, 0, 0, 0, 2, 0, 0),
     ("vv", 1, 0, 0, 3, 2, 0, 0)] +
    [("vv", 1, 0, 0, 0, 0, 1, 0), ("vx", 1, 1, 0, 0, 1, 1, 0)]
)
RM = ("rne", "rtz", "rdn", "rup", "rmm")


def name(t):
    form, sc, alt, rm, lg, lmul, masked, garbage = t
    return (f"{form}_{'s' if sc else 'u'}_a{alt}_{RM[rm]}_e{1 << lg}_m{1 << lmul}"
            + ("_mask" if masked else "") + ("_hi" if garbage else ""))


def scale(rng):
    u = rng.random()
    if u < 0.1:
        return rng.choice([s for pair in EDGE_S for s in pair])
    if u < 0.75:
        return rng.randint(122, 134)
    return rng.randint(1, 254)


def make(rng, t):
    form, sc, alt, rm, lg, lmul, masked, garbage = t
    fi = FP8_STANDARDS[STD][f"altfmt{alt}"]
    fin = finite_codes(fi)
    code = lambda: rng.randrange(256) if rng.random() < 0.12 else rng.choice(fin)
    per = LANES << lmul
    strips = N // per
    sa = [rng.randrange(256) for _ in range(32 * strips)]
    sb = [rng.randrange(256) for _ in range(32 * strips)]
    for q in range(strips):
        for k in range(per >> lg):
            sa[32 * q + k] = scale(rng)
            sb[32 * q + k] = scale(rng)
    a = [pack([code() for _ in range(4)]) for _ in range(N)]
    b = [pack([code() for _ in range(4)]) for _ in range(N)]
    f = []
    for q in range(strips):
        hi = rng.getrandbits(24) if garbage else 0
        f += [pack([code() for _ in range(4)]), scale(rng) | hi << 8]
    m = [rng.randrange(256) for _ in range(4 * strips)]
    c, out = [], []
    for i in range(N):
        q, l = divmod(i, per)
        s_a = sa[32 * q + (l >> lg)] if sc else 128
        if form == "vv":
            bb, s_b = b[i], (sb[32 * q + (l >> lg)] if sc else 128)
        else:
            bb, s_b = f[2 * q], ((f[2 * q + 1] & 255) if sc else 128)
        z = dot(fi, a[i], bb, s_a, s_b)
        ci = rng.choice((0, 0x80000000, 0x3F800000)) if rng.random() < 0.15 else near_c(rng, z)
        c.append(ci)
        on = not masked or (m[4 * q + l // 8] >> (l % 8)) & 1
        out.append(expect(STD, fi, a[i], bb, ci, s_a, s_b, rm) if on else ci)
    arrays = {"_a": (a, 4), "_sa": (sa, 1), "_c": (c, 4), "_out": (out, 4)}
    if form == "vv":
        arrays.update({"_b": (b, 4), "_sb": (sb, 1)})
    else:
        arrays["_f"] = (f, 4)
    if masked:
        arrays["_m"] = (m, 1)
    return arrays


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--outdir", default=os.path.join(HERE, ".."))
    args = ap.parse_args()
    rng = random.Random(1)
    lines = []
    with open(os.path.join(args.outdir, "data.S"), "w") as out:
        print_header(out, "Generated by gen_data.py (gfloat reference). Do not edit.")
        for t in TESTS:
            n = name(t)
            form, sc, alt, rm, lg, lmul, masked, garbage = t
            lines.append(f"DOT_{form.upper()}({n}, {sc}, {alt}, {rm}, {lg}, {lmul}, {masked})")
            for suffix, (vals, esize) in make(rng, t).items():
                print_array(out, n, suffix, vals, esize)
    with open(os.path.join(args.outdir, "tests.h"), "w") as h:
        h.write("// Generated by gen_data.py. Do not edit.\n")
        h.write("// DOT_<form>(name, scaled, altfmt, frm, log2 E, log2 LMUL, masked)\n")
        h.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
