#!/usr/bin/env python3
"""Generate vec-block-cover/data.S and tests.h: scaled mode (docs/scaled-mode.md)
beyond vec-block's single unmasked LMUL-1 instruction.

  ./gen_data.py --std p3109 -o ..

Same reference as vec-block (its gen_data.py: omegaBlockDecode, one rounding,
omegaBlockProject); this file adds register groups, masks and tails:

  lmul  LMUL 2, 4 and 8: a block operand's data group vN..vN+L-1 takes its
        scales from the group vN+L..vN+2L-1, element i of the group from byte
        i >> log2(E) of that L-register scale area (E < L: bytes in the later
        scale registers)
  mask  LMUL 1, vm = 0 with a random v0, mask undisturbed: inactive elements
        keep vd's old value
  tail  LMUL 1, vl = 21 of 32, tail undisturbed (and masked)

Each test's arrays are strip-major, VLs = 32 L elements per strip; a strip's
scales are the VLs bytes loaded into its scale group.
"""
import argparse
import importlib.util
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("vb", os.path.join(HERE, "..", "..", "vec-block", "gen_data", "gen_data.py"))
VB = importlib.util.module_from_spec(spec)
spec.loader.exec_module(VB)
R, FRM = VB.R, VB.FRM

COUNT = 256   # elements per test; main.c's N
TAIL_VL = 21

# kind, mnemonic template, P3109 operation (vec-block's TESTS)
OPS = {
    "add_vv":   ("K8", "vfadd.vv {d}, {a}, {b}"),
    "mul_vv":   ("K8", "vfmul.vv {d}, {a}, {b}"),
    "macc_vv":  ("K8", "vfmacc.vv {d}, {b}, {a}"),
    "madd_vv":  ("K8", "vfmadd.vv {d}, {b}, {a}"),
    "mul_vf":   ("K8F", "vfmul.vf {d}, {a}, f0"),
    "wmul_vv":  ("KW", "vfwmul.vv {d}, {a}, {b}"),
    "wmacc_vv": ("KW", "vfwmacc.vv {d}, {b}, {a}"),
    "wcvt":     ("KWCVT", ".insn r 0x57, 0x1, {f7}, x{dn}, x13, x{an}"),
    "ncvt":     ("KNCVT", ".insn r 0x57, 0x1, {f7}, x{dn}, x29, x{an}"),
}
# registers (a = vs2, b = vs1, d = vd) per kind and LMUL; scales follow each block
LAYOUT = {
    ("K8", 1): (2, 4, 8), ("K8", 2): (2, 6, 10), ("K8", 4): (4, 12, 20),
    ("K8F", 8): (0, None, 16),
    ("KW", 1): (2, 4, 8), ("KW", 2): (2, 6, 12), ("KW", 4): (4, 12, 24),
    ("KWCVT", 2): (2, None, 8), ("KWCVT", 4): (4, None, 16),
    ("KNCVT", 1): (16, None, 8), ("KNCVT", 2): (8, None, 2), ("KNCVT", 4): (16, None, 4),
}

# (op, LMUL, log2 E, variant): variant "" (vl = VLMAX, unmasked), "mask", "tail"
RUNS = []
for L in (2, 4):
    for op in ("add_vv", "mul_vv", "macc_vv", "madd_vv", "wmul_vv", "wmacc_vv", "wcvt", "ncvt"):
        for lb in (0, 5):
            RUNS.append((op, L, lb, ""))
for op in ("add_vv", "wmacc_vv", "ncvt"):
    RUNS.append((op, 4, 1, ""))                       # E = 2 < L: 64 scale bytes, two registers
for lb in (0, 1, 5):
    RUNS.append(("mul_vf", 8, lb, ""))                # LMUL 8: v0-v7 data, v8-v15 scales, vd v16, v24
for op in ("add_vv", "macc_vv", "wmul_vv", "ncvt"):
    for lb in (0, 3):
        RUNS.append((op, 1, lb, "mask"))
for op in ("add_vv", "wmacc_vv", "ncvt"):
    RUNS.append((op, 1, 0, "tail"))


def regs(kind, L, masked):
    a, b, d = LAYOUT[(kind, L)]
    vm = ", v0.t" if masked else ""
    return a, b, d, vm


def emit(outdir, std, count):
    rng = random.Random(7)
    lines = []
    with open(os.path.join(outdir, "data.S"), "w") as out:
        VB.print_header(out, f"Generated by gen_data.py --std {std} (gfloat reference). Do not edit.")
        for k, (op, L, lb, var) in enumerate(RUNS):
            kind, tmpl = OPS[op]
            alt = k % 2
            mode = list(FRM)[k % 5] if var == "" else "rne"
            frm, rnd = FRM[mode]
            fi = VB.FP8_STANDARDS[std][f"altfmt{alt}"]
            masked = var in ("mask", "tail")
            vl = TAIL_VL if var == "tail" else 32 * L
            a, b, d, vm = regs(kind, L, masked)
            insn = tmpl.format(a=f"v{a}", b=f"v{b}", d=f"v{d}", an=a, dn=d, f7="0x24" if masked else "0x25") + \
                ("" if tmpl.startswith(".insn") else vm)
            t = f"{op}_m{L}_b{1 << lb}_a{alt}_{mode}" + (f"_{var}" if var else "")
            sc = lambda r: f'"v{r + L}"' if r is not None else '""'
            lines.append(f'{kind}({t}, {frm}, {alt}, {lb}, {L}, {vl}, {int(masked)}, '
                         f'"v{a}", {sc(a) if kind != "KNCVT" else chr(34) * 2}, '
                         f'"v{b}" , {sc(b)}, '.replace('"vNone" , ""', '"", ""') +
                         f'"v{d}", {sc(d) if kind in ("K8", "K8F", "KNCVT") else chr(34) * 2}, "{insn}")')
            for suffix, (vals, esize) in make(rng, op, kind, fi, std, rnd, lb, L, vl, masked, count).items():
                VB.print_array(out, t, suffix, vals, esize)
    with open(os.path.join(outdir, "tests.h"), "w") as h:
        h.write(f"// Generated by gen_data.py --std {std}. Do not edit.\n")
        h.write("// kind(name, frm, altfmt, log2 E, LMUL, vl, masked, vs2, its scales, vs1, its scales, vd, its scales, instruction)\n")
        h.write("\n".join(lines) + "\n")
    return len(RUNS)


def make(rng, name, kind, fi, std, rnd, lb, L, vl, masked, count):
    VLs = 32 * L
    code8 = lambda: rng.randrange(256)
    ex = lambda c: R.exact(fi, c)
    nblk = max(1, VLs >> lb)

    def scales(centres):
        arr = [code8() for _ in range(count)]
        for q in range(count // VLs):
            for bk in range(nblk):
                arr[q * VLs + bk] = centres(q, bk)
        return arr

    def at(arr, i):
        return arr[(i // VLs) * VLs + ((i % VLs) >> lb)]

    # mask: VLs bits per strip, in 32 bytes per strip (one v0 load)
    mbits = [rng.random() < 0.5 for _ in range(count)]
    m = []
    for q in range(count // VLs):
        byts = [sum(mbits[q * VLs + 8 * j + k] << k for k in range(8)) for j in range(VLs // 8)]
        m += byts + [0] * (32 - len(byts))
    active = lambda i: (i % VLs) < vl and (not masked or mbits[i])
    res = {}

    if kind == "KWCVT":
        a = [code8() for _ in range(count)]
        sa = scales(lambda q, bk: VB.rand_scale(rng, 128))
        c = [VB.rand_bf16(rng) for _ in range(count)]
        out = [VB.project16(std, VB.block_decode(ex(a[i]), at(sa, i)), rnd) if active(i) else c[i] for i in range(count)]
        res = {"_a": (a, 1), "_sa": (sa, 1), "_c": (c, 2), "_out": (out, 2)}
    elif kind == "KNCVT":
        a = [VB.rand_bf16(rng, -140, 140) for _ in range(count)]
        def top(q, bk):
            ms = [R.exact(VB.BF16, a[q * VLs + i]) for i in range(VLs) if i >> lb == bk]
            ms = [math.floor(math.log2(x[2])) for x in ms if x[0] == "num" and x[2]]
            return max(ms) if ms else 0
        sr = scales(lambda q, bk: VB.rand_scale(rng, 128 + top(q, bk) - rng.randint(0, 10)))
        c = [code8() for _ in range(count)]
        out = [VB.project8(fi, R.exact(VB.BF16, a[i]), at(sr, i), rnd) if active(i) else c[i] for i in range(count)]
        res = {"_a": (a, 2), "_c": (c, 1), "_sr": (sr, 1), "_out": (out, 1)}
    else:
        op = VB.TESTS[name][2]
        sa = scales(lambda q, bk: VB.rand_scale(rng, 128))
        sb = scales(lambda q, bk: VB.rand_scale(rng, 128))
        adds = name == "add_vv"
        sr = scales(lambda q, bk: VB.rand_scale(rng, max(sa[q * VLs + bk], sb[q * VLs + bk]) if adds
                                               else sa[q * VLs + bk] + sb[q * VLs + bk] - 128))
        f = [code8() for _ in range(count // VLs)]
        a, b, c, out = [], [], [], []
        for i in range(count):
            x2, x1 = code8(), code8()
            A2 = VB.block_decode(ex(x2), at(sa, i))
            A1 = VB.block_decode(ex(x1), at(sb, i))
            F = ex(f[i // VLs])
            if kind in ("K8", "K8F"):
                dd = code8()
                D = VB.block_decode(ex(dd), at(sr, i))
                out.append(VB.project8(fi, op(A2, A1, D, F, rnd), at(sr, i), rnd) if active(i) else dd)
            else:
                dd = VB.rand_bf16(rng)
                out.append(VB.project16(std, op(A2, A1, R.exact(VB.BF16, dd), F, rnd), rnd) if active(i) else dd)
            a.append(x2); b.append(x1); c.append(dd)
        f += [0] * (-len(f) % 4)
        res = {"_a": (a, 1), "_sa": (sa, 1), "_b": (b, 1), "_sb": (sb, 1), "_f": (f, 1), "_out": (out, 1 if kind in ("K8", "K8F") else 2)}
        if kind in ("K8", "K8F"):
            res.update({"_c": (c, 1), "_sr": (sr, 1)})
        else:
            res["_c"] = (c, 2)
    res["_m"] = (m, 1)
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--std", choices=["p3109", "p3109-finite"], default="p3109")
    ap.add_argument("-o", "--outdir", default=os.path.join(HERE, ".."))
    args = ap.parse_args()
    print(emit(args.outdir, args.std, COUNT), "tests")


if __name__ == "__main__":
    main()
